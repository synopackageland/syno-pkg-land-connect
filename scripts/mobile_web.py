#!/usr/bin/env python3
"""The phone browser page: Package Land's launcher, built by the mobile repo.

Connect serves it as m/ beside its own UI module, on DSM's own origin, so a
phone without the App signs in to DSM and opens its Apps there. The SPK keeps
the UI in a content-hashed folder, so the page is a relative build.
The page is the mobile repo's `npm run build:web` output, kept as built in
vendor/mobile-web with its build.json (source commit and each file's SHA-256).

  python3 scripts/mobile_web.py update <mobile repo>   rebuild and vendor it
  python3 scripts/mobile_web.py check                  the vendored files are that build

update also writes vendor/mobile-web-THIRD_PARTY.md: every npm package in the
page's bundles, taken from the source maps of the same export (which are not
kept), with its version, declared license and license files, and each bundled
font's own copyright and license from its name table.
"""
import hashlib, json, os, re, shutil, struct, subprocess, sys, tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
VENDOR = ROOT / 'vendor/mobile-web'
# A relative build: the page works from the hashed folder the SPK puts it in
BASE = './'
SERVED = 'm'
# The fixed address of the page: the ui.stable_pages stub, which forwards to the hashed folder
STABLE_SCOPE = '/webman/3rdparty/SynoPkgConnect/'
STABLE_PAGE = STABLE_SCOPE + SERVED + '/index.html'
NOTICES = ROOT / 'vendor/mobile-web-THIRD_PARTY.md'
NOTICES_HEADER = '<!-- Generated by scripts/mobile_web.py from mobile commit {commit}; do not edit -->'


def check(folder=VENDOR):
    """The build's manifest, or RuntimeError when a file differs from it."""
    folder = Path(folder)
    try:
        build = json.loads((folder / 'build.json').read_text())
    except (OSError, ValueError) as error:
        raise RuntimeError(f'mobile web build: no readable build.json in {folder}') from error
    if build.get('schema') != 1 or not isinstance(build.get('files'), dict):
        raise RuntimeError('mobile web build: unknown build.json schema')
    if build.get('base') != BASE:
        raise RuntimeError(f"mobile web build: built for {build.get('base')}; Connect needs a relative build")
    if build.get('dirty') is not False or not build.get('commit'):
        raise RuntimeError('mobile web build: not built from a committed mobile source')
    present = {p.relative_to(folder).as_posix() for p in folder.rglob('*') if p.is_file() and p.name != 'build.json'}
    listed = set(build['files'])
    if present != listed:
        raise RuntimeError('mobile web build: files differ from build.json: ' + ', '.join(sorted(present ^ listed)))
    for name, digest in build['files'].items():
        if hashlib.sha256((folder / name).read_bytes()).hexdigest() != digest:
            raise RuntimeError(f'mobile web build: {name} differs from build.json')
    if 'index.html' not in listed or 'manifest.webmanifest' not in listed:
        raise RuntimeError('mobile web build: index.html or manifest.webmanifest is missing')
    if Path(folder) == VENDOR:
        try:
            first = NOTICES.read_text().split('\n', 1)[0]
        except OSError as error:
            raise RuntimeError('mobile web build: no third-party notices; run update') from error
        if first != NOTICES_HEADER.format(commit=build['commit']):
            raise RuntimeError('mobile web build: third-party notices are for another build; run update')
    return build


def install(ui_dir, folder=VENDOR):
    """Copy the checked page into the built UI directory.

    The copy's PWA manifest opens the fixed address (ui.stable_pages), not the
    hashed folder it is served from, so an icon on a home screen keeps working
    after an update. The vendored files stay as built.
    """
    check(folder)
    target = Path(ui_dir) / SERVED
    shutil.rmtree(target, ignore_errors=True)
    shutil.copytree(folder, target)
    manifest = target / 'manifest.webmanifest'
    data = json.loads(manifest.read_text())
    data.update(start_url=STABLE_PAGE, scope=STABLE_SCOPE)
    manifest.write_text(json.dumps(data, indent=2, ensure_ascii=False) + '\n')


def source_maps(maps):
    def walk(m):
        return m['sources'] if 'sources' in m else [s for section in m.get('sections', []) for s in walk(section['map'])]
    return [s for p in Path(maps).rglob('*.map') for s in walk(json.loads(p.read_text()))]


PACKAGE = re.compile(r'/?(.*node_modules/(?:@[^/]+/)?[^/]+)/')


def bundled_packages(mobile, sources):
    """Package folders (innermost node_modules entry) of every bundled source."""
    found = set()
    for source in sources:
        m = PACKAGE.match(source)
        if m and (Path(mobile) / m.group(1) / 'package.json').is_file():
            found.add(m.group(1))
    return sorted(found, key=lambda d: (d.rsplit('node_modules/', 1)[1], d))


def font_names(path):
    """Copyright (name ID 0), license (13) and license URL (14) from a TrueType name table."""
    data = Path(path).read_bytes()
    tables = {data[12 + 16 * i:16 + 16 * i]: struct.unpack('>II', data[20 + 16 * i:28 + 16 * i]) for i in range(struct.unpack('>H', data[4:6])[0])}
    start = tables[b'name'][0]
    count, strings = struct.unpack('>HH', data[start + 2:start + 6])
    names = {}
    for i in range(count):
        platform, _, _, name, length, offset = struct.unpack('>6H', data[start + 6 + 12 * i:start + 18 + 12 * i])
        raw = data[start + strings + offset:start + strings + offset + length]
        if name in (0, 13, 14) and name not in names:
            names[name] = raw.decode('utf-16-be' if platform in (0, 3) else 'latin-1').strip()
    return names


LICENSE_FILE = re.compile(r'(?i)^(licen[cs]e|copying|notice)')


def license_files(folder):
    return sorted(p for p in Path(folder).iterdir() if p.is_file() and LICENSE_FILE.match(p.name))


def nested_licenses(mobile, package, sources):
    """License files of vendored code inside a package: folders between a bundled file and the package root."""
    root, found = (Path(mobile) / package).resolve(), set()
    for source in sources:
        m = PACKAGE.match(source)
        if not m or m.group(1) != package:
            continue
        folder = (Path(mobile) / source.lstrip('/')).resolve().parent
        while folder != root and root in folder.parents:
            found.update(license_files(folder))
            folder = folder.parent
    return sorted(found)


def font_source(path, folder):
    """The node_modules file an exported font asset was copied from (the export adds a content hash)."""
    relative = Path(path).relative_to(folder).as_posix()
    return re.sub(r'^assets/', '', re.sub(r'\.[0-9a-f]{32}(\.ttf)$', r'\1', relative))


def notices(mobile, sources, commit, folder=VENDOR):
    fonts = sorted(Path(folder).rglob('*.ttf'))
    sources = list(sources) + [font_source(f, folder) for f in fonts]
    lines = [NOTICES_HEADER.format(commit=commit), '', '# Third-party software in the phone browser page (m/)', '',
             'Syno Package Land mobile, built for browsers, includes these npm packages and fonts.', '']
    for d in bundled_packages(mobile, sources):
        folder_path = Path(mobile) / d
        pkg = json.loads((folder_path / 'package.json').read_text())
        lines += [f"## {pkg['name']} {pkg.get('version', '')}", '', f"License: {pkg.get('license') or 'not declared'}", '']
        files = license_files(folder_path)
        for f in files:
            lines += ['```', f.read_text(errors='replace').strip(), '```', '']
        if not files:
            lines += ['The package ships no license file; the license above is its package.json declaration.', '']
        for f in nested_licenses(mobile, d, sources):
            lines += [f'Vendored in {f.parent.relative_to(folder_path.resolve()).as_posix()}:', '', '```', f.read_text(errors='replace').strip(), '```', '']
    for font in fonts:
        names = font_names(font)
        lines += [f'## Font {font.name.split(".")[0]}', '', f'From {font_source(font, folder)}.', '']
        lines += [names[k] + '\n' for k in (0, 13, 14) if names.get(k)]
        if not names.get(13):
            lines += ["The font's name table has no license entry; it ships under its package's license above.", '']
    return '\n'.join(lines).rstrip() + '\n'


def entry_bundle(folder=VENDOR):
    """The script index.html loads, relative to the page."""
    found = re.findall(r'<script src="\./([^"]+)"', (Path(folder) / 'index.html').read_text())
    if len(found) != 1:
        raise RuntimeError('mobile web build: index.html must load one script')
    return found[0]


def point_ignore(manifest=ROOT / 'dsm-package.yaml'):
    """Name the current entry bundle in its reviewed ui_secret_ignores entry."""
    text = manifest.read_text()
    pattern = r'(- file: "app/' + re.escape(SERVED) + r'/_expo/static/js/web/)index-[0-9a-f]+\.js(")'
    changed, count = re.subn(pattern, lambda m: m.group(1) + entry_bundle().split('/')[-1] + m.group(2), text)
    if count != 1:
        raise RuntimeError('mobile web build: dsm-package.yaml needs one ui_secret_ignores entry for the bundle')
    manifest.write_text(changed)


def update(mobile):
    mobile = Path(mobile).resolve()
    if subprocess.run(['git', 'status', '--porcelain'], cwd=mobile, capture_output=True, text=True, check=True).stdout.strip():
        raise RuntimeError('mobile web build: commit the mobile repo first')
    env = {k: v for k, v in os.environ.items() if k != 'WEB_BASE_URL'}
    subprocess.run(['npm', 'run', 'build:web'], cwd=mobile, env=env, check=True)
    built = mobile / 'dist/web'
    build = check(built)
    # The same export with source maps names every bundled module; the maps are not kept
    with tempfile.TemporaryDirectory(prefix='mobile-web-maps-') as maps:
        subprocess.run(['npx', 'expo', 'export', '--platform', 'web', '--source-maps', '--output-dir', maps], cwd=mobile, env=env, check=True)
        sources = source_maps(maps)
    shutil.rmtree(VENDOR, ignore_errors=True)
    shutil.copytree(built, VENDOR)
    NOTICES.write_text(notices(mobile, sources, build['commit']))
    point_ignore()
    print(json.dumps({k: v for k, v in check().items() if k != 'files'}))


if __name__ == '__main__':
    if sys.argv[1:2] == ['check'] and len(sys.argv) == 2:
        build = check()
        print(f"mobile web build {build.get('version')} ({build['commit'][:12]}): {len(build['files'])} files match")
    elif sys.argv[1:2] == ['update'] and len(sys.argv) == 3:
        update(sys.argv[2])
    else:
        sys.exit(__doc__)
